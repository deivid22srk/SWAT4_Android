#!/usr/bin/env python3
"""Emit runtime/modules.c and ci/gen_stub/* from tools/swat4_modules.py.

Run after editing the manifest; the output is committed so the app-only build
works without the user's game files.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from swat4_modules import MODULES, EXE

ALL = [EXE] + MODULES          # exe first (index 0), then DLL load order


def emit_modules_c():
    lines = []
    w = lines.append
    w("/* Recompiled modules linked into this build.")
    w(" * GENERATED by tools/emit_modules.py from tools/swat4_modules.py.")
    w(" * Edit the manifest, not this file. */")
    w('#include "game.h"')
    w('#include "rt_table.h"')
    w("")
    for mid, fname, base, kind in ALL:
        w(f"extern const FnEntry g_fn_table_{mid}[];")
        w(f"extern const unsigned g_fn_count_{mid};")
    w("")
    w("enum {")
    for i, (mid, *_ ) in enumerate(ALL):
        w(f"    M_{mid} = {i},")
    w("    M_COUNT")
    w("};")
    w("")
    w("const FnModule g_modules[] = {")
    for mid, fname, base, kind in ALL:
        name = "GAME_EXE" if kind == "exe" else f'"{fname}"'
        w(f"    {{{name}, g_fn_table_{mid}, 0}},")
    w("};")
    w("const unsigned g_nmodules = sizeof g_modules / sizeof g_modules[0];")
    w("")
    w("unsigned rt_module_count(unsigned m) {")
    w("    switch (m) {")
    for mid, *_ in ALL:
        w(f"    case M_{mid}: return g_fn_count_{mid};")
    w("    default: return 0;")
    w("    }")
    w("}")
    w("")
    w("/* DLLs loaded before the exe, dependencies first. */")
    w("const char *const g_dll_modules[] = {")
    for mid, fname, base, kind in MODULES:
        w(f'    "{fname}",')
    w("    NULL,")
    w("};")
    w("const uint32_t g_dll_bases[] = {")
    for mid, fname, base, kind in MODULES:
        w(f"    0x{base:08X}u,")
    w("    0u,")
    w("};")
    return "\n".join(lines) + "\n"


def emit_stub():
    d = os.path.join(ROOT, "ci", "gen_stub")
    os.makedirs(d, exist_ok=True)
    keep = set()
    for mid, fname, base, kind in ALL:
        name = f"{mid}_table.c"
        keep.add(name)
        p = os.path.join(d, name)
        with open(p, "w") as f:
            f.write('/* app-only stub: no functions were recompiled for this module.\n'
                    ' * The launcher validates the folder; the game stops at the first\n'
                    ' * recompiled function with a clear message. */\n'
                    '#include "rt_table.h"\n'
                    f"const FnEntry g_fn_table_{mid}[1] = {{{{0, 0}}}};\n"
                    f"const unsigned g_fn_count_{mid} = 0;\n")
    # Remove stale stubs from a previous game target.
    for n in os.listdir(d):
        if n.endswith("_table.c") and n not in keep:
            os.remove(os.path.join(d, n))
    with open(os.path.join(d, "README.md"), "w") as f:
        f.write("# ci/gen_stub\n\n"
                "Empty function tables used by the **app-only** CI build. This is not\n"
                "game code: it lets the APK compile, install and validate the game\n"
                "folder. The full build replaces this directory with `gen/` generated\n"
                "from the user's own copy (see `tools/push_gen.sh`).\n")


if __name__ == "__main__":
    with open(os.path.join(ROOT, "runtime", "modules.c"), "w") as f:
        f.write(emit_modules_c())
    emit_stub()
    print("wrote runtime/modules.c and ci/gen_stub/")